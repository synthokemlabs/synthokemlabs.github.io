/**
 * Renders brand-styled 2D structure SVGs from structures.json using RDKit (build-time only).
 * Output: public/structures/svg/<slug>.svg — bonds carry pathLength=1 + an index so they can
 * "draw themselves" with CSS when inlined.
 * Run: node scripts/render-structures.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import initRDKitModule from "@rdkit/rdkit";

const RDKit = await initRDKitModule();
const data = JSON.parse(readFileSync(new URL("../src/data/structures.json", import.meta.url), "utf8"));
const outDir = new URL("../public/structures/svg/", import.meta.url);
mkdirSync(outDir, { recursive: true });

const rgb = (h) => [1, 3, 5].map((i) => +(parseInt(h.slice(i, i + 2), 16) / 255).toFixed(3));
const palette = {
  6: rgb("#0e1a21"), 1: rgb("#4f5f69"), 7: rgb("#0868a8"), 8: rgb("#c2410c"), 9: rgb("#0f7a8a"),
  15: rgb("#b45309"), 16: rgb("#a16207"), 17: rgb("#15803d"), 11: rgb("#6d28d9"), 19: rgb("#6d28d9"), 20: rgb("#6d28d9"),
};

/**
 * Crop the 420×300 canvas to the molecule's bounding box so every structure fills its frame
 * consistently. A minimum frame (210×150) stops very small molecules being blown up.
 */
function cropToContent(svg) {
  const pts = [];
  for (const m of svg.matchAll(/ d='([^']*)'/g)) {
    const v = (m[1].match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
    for (let k = 0; k + 1 < v.length; k += 2) pts.push([v[k], v[k + 1]]);
  }
  for (const m of svg.matchAll(/<ellipse[^>]*cx='([\d.]+)' cy='([\d.]+)' rx='([\d.]+)'/g)) {
    const [cx, cy, rx] = [+m[1], +m[2], +m[3]];
    pts.push([cx - rx, cy - rx], [cx + rx, cy + rx]);
  }
  if (!pts.length) return svg;
  const PAD = 10, MIN_W = 210, MIN_H = 150;
  let x0 = Math.min(...pts.map((p) => p[0])) - PAD, x1 = Math.max(...pts.map((p) => p[0])) + PAD;
  let y0 = Math.min(...pts.map((p) => p[1])) - PAD, y1 = Math.max(...pts.map((p) => p[1])) + PAD;
  if (x1 - x0 < MIN_W) { const c = (x0 + x1) / 2; x0 = c - MIN_W / 2; x1 = c + MIN_W / 2; }
  if (y1 - y0 < MIN_H) { const c = (y0 + y1) / 2; y0 = c - MIN_H / 2; y1 = c + MIN_H / 2; }
  const vb = [x0, y0, x1 - x0, y1 - y0].map((n) => +n.toFixed(1)).join(" ");
  // Explicit intrinsic size so <img object-fit: contain> scales identically in every browser
  return svg.replace(/viewBox='[^']*'/, `width='${Math.round(x1 - x0)}' height='${Math.round(y1 - y0)}' viewBox='${vb}'`);
}

let n = 0;
for (const [slug, s] of Object.entries(data)) {
  // Name-matched records may be hydrates; the company's CAS refers to the anhydrous form, so drop water fragments.
  const smiles = s.matchedBy === "name" ? s.smiles.split(".").filter((f) => f !== "O").join(".") : s.smiles;
  const mol = RDKit.get_mol(smiles);
  if (!mol || !mol.is_valid()) { console.log("✗", slug); continue; }
  let svg = mol.get_svg_with_highlights(JSON.stringify({
    width: 420, height: 300, clearBackground: false, bondLineWidth: 1.6, padding: 0.06, fixedBondLength: 30,
    baseFontSize: 0.62, atomColourPalette: palette, addStereoAnnotation: false, fixedFontSize: -1,
  }));
  mol.delete();
  let i = 0;
  svg = svg
    .replace(/<\?xml[^>]*>\s*/, "")
    .replace(/<rect[^>]*\/>\s*/g, "")
    .replace(/width='\d+px' height='\d+px' viewBox/, "viewBox")
    .replace(/<path (class='bond-[^']*') d='([^']*)' style='/g, (_m, c, d) => `<path ${c} d='${d}' pathLength='1' style='--i:${i++};`)
    .replace(/<!-- END OF HEADER -->/, "");
  svg = cropToContent(svg);
  writeFileSync(new URL(`${slug}.svg`, outDir), svg);
  n++;
}
// Light index for client components (no 3D data). Formula/MW only for CAS-matched records.
const index = Object.fromEntries(Object.entries(data).map(([slug, v]) => [slug, v.matchedBy === "name" ? {} : { formula: v.formula, mw: v.mw }]));
writeFileSync(
  new URL("../src/data/structure-index.ts", import.meta.url),
  `/** Generated by scripts/render-structures.mjs — do not edit. Products with a rendered 2D structure in public/structures/svg. */\nexport const STRUCTURE_INDEX: Record<string, { formula?: string; mw?: string }> = ${JSON.stringify(index, null, 1)};\n`,
);
console.log("rendered", n);
